def translate_text(text: str) -> str:
    if _language != "en" or not text:
        return text
    translated = text
    for source, target in sorted(_EN_REPLACEMENTS, key=lambda pair: len(pair[0]), reverse=True):
        translated = translated.replace(source, target)
    translated = re.sub(r"(?<=[0-9sm])前", " ago", translated)
    translated = translated.replace("。", ".").replace("；", "; ").replace("，", ", ")
    return translated
